def package_files(hub: Path) -> dict[str, str]:
    """Per-file SHA-256 of everything that defines the artifact (weights, index,
    config, tokenizer files, remote-code modules), RECURSIVE over the hub directory;
    README.md and cache directories excluded."""
    out = {}
    for p in sorted(hub.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(hub)
        if rel.name in SKIP_FILES or set(rel.parts[:-1]) & SKIP_DIRS:
            continue
        out[rel.as_posix()] = screen._sha256(p)
    return out


def package_fingerprint(files: dict[str, str]) -> str:
    h = hashlib.sha256()
    for name in sorted(files):
        h.update(f"{name}\n{files[name]}\n".encode())
    return h.hexdigest()


def checker_hashes() -> dict[str, str]:
    return {f: screen._sha256(ROOT / f) for f in CHECKER_FILES}


