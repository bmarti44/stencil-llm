def build_arm(model, tokenizer, mc, dialogue, item, arm, research_base, max_new):
    """Build the prompt for one arm through the package and assert the paired
    equality (both arms == research base count) and the 4,096-token allocation."""
    query = item["queries"][0]
    head, sep, request = mc.long_request(dialogue, query)
    session = model.new_session(tokenizer, stencil_focus=(arm == "focus"))
    for role, text, rendered in mc.focus_session_messages(dialogue, item["session"]):
        session.add_message(role, text, rendered=rendered)
    prompt = session.build_prompt(request, head=head, separator=sep)
    built = dict(session.last)
    if built["prompt_tokens"] != research_base:
        raise SystemExit(
            f"item {item['id']} arm {arm}: package prompt {built['prompt_tokens']} "
            f"tokens != research base {research_base}"
        )
    if built["prompt_tokens"] + max_new > 4096:
        raise SystemExit(f"item {item['id']}: prompt + output exceeds 4096 tokens")
    return session, prompt, built, (head, sep, request)


def reminder_sources(session, built: dict, head: str, sep: str, request: str) -> dict:
    """Provenance of the rendered reminder (finding 10; result-audit finding 1): the
    package selects evicted sentences against the BASE-window boundary (the plain
    window's cut, ``focus_session.build_prompt``), so the boundary is recomputed from
    the base fit, not from the shortened focus window. Records absolute character
    spans of the kept sentences in the thread, their message index, the boundary and a
    digest of the thread text; the kept spans must reproduce the reminder lines."""
    thread = session.thread()
    base = session._fit(head, thread, sep, "", request)
    cut = max(len(thread) - len(base["thread_text_kept"]), 0)
    # message index of every instruction span (same offset arithmetic as the package)
    bounds = []
    offset = 0
    for mi, m in enumerate(session.messages):
        bounds.append((offset, offset + len(m["rendered"]), mi))
        offset += len(m["rendered"])
    spans = []
    for start, end, sentence in session.instruction_spans():
        mi = next(i for (lo, hi, i) in bounds if lo <= start < hi)
        spans.append((start, end, mi, sentence))
    spans = sorted(set(spans))
    evicted = [s for s in spans if s[1] <= cut]
    k = built.get("kept_sentences", 0) or 0
    kept = evicted[-k:] if k else []
    reminder = built.get("reminder", "")
    lines = reminder.split("\n")[1:] if reminder else []
    if [f"- {txt}" for _, _, _, txt in kept] != lines:
        raise SystemExit("reminder provenance does not reproduce the reminder")
    return {
        "thread_chars": len(thread),
        "thread_sha256": hashlib.sha256(thread.encode()).hexdigest(),
        "eviction_boundary_char": cut,
        "evicted_spans": len(evicted),
        "kept_spans": [
            {"start": s, "end": e, "message_index": mi, "sentence": txt}
            for s, e, mi, txt in kept
        ],
    }


# ------------------------------------------------------------------ receipts
class ProcessReceipt:
    """Durable heartbeat receipt for one owned GPU process plus the watchdog that
    ends the process when a registered limit is crossed (finding 3).

    ``<dir>/process-<utc>-<pid>.json`` is rewritten every ``BEAT_INTERVAL`` seconds
    with the elapsed resident time; a process that dies leaves ``ended`` null, and
    its resident time is bounded above by the last beat plus one interval.
    """

    def __init__(
        self,
        out_dir: Path,
        kind: str,
        resident_limit: float | None,
        overhead_limit: float | None = None,
        prior_overhead: float = 0.0,
        call_limit: float | None = None,
    ) -> None:
        self.dir = Path(out_dir)
        self.dir.mkdir(parents=True, exist_ok=True)
        self.kind = kind
        self.pid = os.getpid()
        self.started_utc = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        self.path = self.dir / f"process-{self.started_utc}-{self.pid}.json"
        self.t0 = time.monotonic()
        self.resident_limit = resident_limit
        self.overhead_limit = overhead_limit
        self.prior_overhead = prior_overhead
        self.call_limit = call_limit
        self.generation_seconds = 0.0
        self.call_started: float | None = None
        self.ended: str | None = None
        self._lock = threading.Lock()
        self._stop = threading.Event()
        self.write()
        self._thread = threading.Thread(target=self._beat, daemon=True)
        self._thread.start()

    def elapsed(self) -> float:
        return time.monotonic() - self.t0

    def overhead(self) -> float:
        cur = (
            self.elapsed() - self.call_started if self.call_started is not None else 0.0
        )
        return self.elapsed() - self.generation_seconds - cur

    def payload(self) -> dict:
        return {
            "kind": self.kind,
            "pid": self.pid,
            "started_utc": self.started_utc,
            "elapsed": self.elapsed(),
            "last_beat_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "beat_interval": BEAT_INTERVAL,
            "generation_seconds": self.generation_seconds,
            "current_call_started": self.call_started,
            "overhead_seconds": self.overhead(),
            "limits": {
                "resident": self.resident_limit,
                "overhead_cumulative": self.overhead_limit,
                "call": self.call_limit,
            },
            "ended": self.ended,
        }

    def write(self) -> None:
        with self._lock:
            screen._write_atomic(self.path, self.payload())

    def _violation(self) -> str | None:
        if self.resident_limit is not None and self.elapsed() > self.resident_limit:
            return "watchdog:resident"
        if (
            self.overhead_limit is not None
            and self.prior_overhead + self.overhead() > self.overhead_limit
        ):
            return "watchdog:overhead"
        if (
            self.call_limit is not None
            and self.call_started is not None
            and self.elapsed() - self.call_started > self.call_limit
        ):
            return "watchdog:call"
        return None

    def _beat(self) -> None:
        while not self._stop.wait(BEAT_INTERVAL):
            why = self._violation()
            if why:
                self.ended = why
                self.write()
                print(f"{why}: ending process {self.pid}", flush=True)
                os._exit(3)
            self.write()

    def begin_call(self) -> float:
        self.call_started = self.elapsed()
        self.write()
        return self.call_started

    def end_call(self, seconds: float) -> None:
        self.generation_seconds += seconds
        self.call_started = None
        self.write()

    def finish(self, how: str = "clean") -> None:
        self._stop.set()
        self.ended = how
        self.write()


def process_receipts(out_dir: Path) -> list[dict]:
    rows = []
    for p in sorted(Path(out_dir).glob("process-*.json")):
        try:
            row = json.loads(p.read_text())
        except json.JSONDecodeError:
            row = {"malformed": True, "elapsed": None, "ended": None}
        row["file"] = p.name
        rows.append(row)
    return rows


def resident_seconds(out_dir: Path) -> dict:
    """Resident time over every process receipt; a receipt without ``ended`` is
    bounded by its last beat plus one interval and counted as interrupted."""
    total = overhead = gen = 0.0
    open_count = 0
    unbounded = False
    for r in process_receipts(out_dir):
        if r.get("malformed") or r.get("elapsed") is None:
            unbounded = True
            continue
        bound = float(r["elapsed"])
        if not r.get("ended"):
            bound += float(r.get("beat_interval", BEAT_INTERVAL))
            open_count += 1
        total += bound
        gen += float(r.get("generation_seconds", 0.0))
        overhead += float(r.get("overhead_seconds", 0.0))
    return {
        "resident_seconds": total,
        "overhead_seconds": overhead,
        "generation_seconds_in_receipts": gen,
        "processes": len(process_receipts(out_dir)),
        "interrupted_processes": open_count,
        "unbounded": unbounded,
    }


def attempt(out_dir: Path, payload: dict) -> None:
    with (out_dir / "attempts.jsonl").open("a") as f:
        f.write(json.dumps(payload) + "\n")
        f.flush()
        os.fsync(f.fileno())


def attempt_rows(out_dir: Path) -> list[dict]:
    log = Path(out_dir) / "attempts.jsonl"
    if not log.exists():
        return []
    rows = []
    for line in log.read_text().splitlines():
        if line.strip():
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError:
                rows.append({"event": "malformed"})
    return rows


def attempt_accounting(out_dir: Path, deadline: float = screen.DEADLINE) -> dict:
    """Generation spending derived from the attempt log alone (finding 4): every
    ended attempt counts its measured seconds exactly once (scored or not); an open
    attempt counts the time until its process's last heartbeat plus one interval;
    an open attempt whose process receipt is missing is UNBOUNDED (the summary
    cannot establish budget compliance)."""
    receipts = {r["file"]: r for r in process_receipts(out_dir)}
    started: dict[str, dict] = {}
    completed = 0.0
    n_completed = 0
    open_seconds = 0.0
    n_open = 0
    unbounded = False
    for row in attempt_rows(out_dir):
        ev = row.get("event")
        if ev == "start":
            started[row["attempt_id"]] = row
        elif ev == "end":
            started.pop(row["attempt_id"], None)
            completed += float(row["seconds"])
            n_completed += 1
        else:
            unbounded = True
    for row in started.values():
        n_open += 1
        rec = receipts.get(row.get("process"))
        if rec is None or rec.get("elapsed") is None:
            unbounded = True
            open_seconds += deadline + CALL_GRACE
            continue
        bound = float(rec["elapsed"]) + (
            0.0 if rec.get("ended") else float(rec.get("beat_interval", BEAT_INTERVAL))
        )
        open_seconds += max(bound - float(row["process_elapsed"]), 0.0)
    return {
        "completed_seconds": completed,
        "n_completed": n_completed,
        "open_seconds": open_seconds,
        "n_open": n_open,
        "unbounded": unbounded,
        "generation_seconds": completed + open_seconds,
    }


def ended_attempts(out_dir: Path) -> dict[tuple[str, str], list[dict]]:
    """Ended attempts by (id, arm) with their raw-output file (resume scoring)."""
    out: dict[tuple[str, str], list[dict]] = {}
    for row in attempt_rows(out_dir):
        if row.get("event") == "end":
            out.setdefault((row["id"], row["arm"]), []).append(row)
    return out


def raw_path(out_dir: Path, attempt_id: str) -> Path:
    return Path(out_dir) / "raw" / f"{attempt_id.replace(':', '_')}.json"


# ------------------------------------------------------------------ scoring
def score_raw(raw: dict, item: dict, mc, compute_score) -> dict:
    """Score a saved raw output with the frozen checker (idempotent; used at
    generation time and to resume after a post-generation interruption)."""
    gen = dict(raw["generation"])
    query = item["queries"][0]
    gen["failures"] = mc.output_failures(
        gen["text"], gen["generated_token_ids"], gen["truncated"], gen["timed_out"]
    )
    gen["scores"] = mc.score_generation(
        gen["text"],
        item["history_regex"],
        compute_score,
        required=item["required"][query],
        structure=item["structure"][query],
    )
    if gen["timed_out"]:
        gen["scores"]["strict"] = False
        if gen["scores"].get("fraction_required") is not None:
            gen["scores"]["fraction_required"] = 0.0
    return gen


def arm_record(raw: dict, gen: dict) -> dict:
    built = raw["window"]
    reminder = built.get("reminder", "")
    return {
        "attempt_id": raw["attempt_id"],
        "raw_file": raw["raw_file"],
        "policy": "role_evicted" if raw["arm"] == "focus" else None,
        "selected_sentences": built.get("evicted_sentences", 0),
        "kept_sentences": built.get("kept_sentences", 0),
        "reminder": reminder,
        "reminder_tokens": built.get("reminder_tokens", 0),
        "reminder_empty": not reminder,
        "reminder_sources": raw.get("reminder_sources"),
        "generations": [gen],
        "strict": gen["scores"]["strict"],
        "fraction": gen["scores"]["fraction"],
        "manifest": raw["manifest"],
    }


