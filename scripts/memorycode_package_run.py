def fingerprint_matches(a: dict, b: dict, provisional: bool = False) -> bool:
    """STRICT equality of every registered fingerprint key (review finding 6). A
    provisional match, used only to decide whether loading is worthwhile, tolerates
    the load-resolved fields (attention backend, dtype, device, gpu, EOS) being
    unresolved (None) on either side; nothing else is tolerated."""
    for k in FINGERPRINT_KEYS:
        if k == "environment":
            ea, eb = a.get(k) or {}, b.get(k) or {}
            for kk in REQUIRED_ENV:
                if kk not in ea or kk not in eb:
                    if provisional and kk in LOAD_RESOLVED_ENV:
                        continue
                    return False
                if kk in LOAD_RESOLVED_ENV and (ea[kk] is None or eb[kk] is None):
                    if provisional:
                        continue
                    return False
                if ea[kk] != eb[kk]:
                    return False
        elif k in ("eos_token_ids", "decoding"):
            va, vb = a.get(k), b.get(k)
            if provisional:
                va = _without_eos(va)
                vb = _without_eos(vb)
            if va != vb or va is None:
                return False
        elif a.get(k) != b.get(k) or a.get(k) is None:
            return False
    return True


def _without_eos(v):
    if isinstance(v, dict):
        return {kk: vv for kk, vv in v.items() if kk != "eos_token_id"}
    return "unresolved"


# ------------------------------------------------------------------ generation
def generate_package(session, request, head, sep, max_new, deadline) -> dict:
    """Greedy generation through ``FocusSession.generate``; ``max_time`` bounds the
    call. Only a TERMINAL effective EOS is stripped from the raw ids."""
    started = time.monotonic()
    session.generate(
        request,
        head=head,
        separator=sep,
        max_new_tokens=max_new,
        max_time=deadline,
    )
    seconds = time.monotonic() - started
    raw = list(session.last["generated_token_ids"])
    stops = eos_ids(session.model)
    ended_by_eos = bool(raw) and raw[-1] in stops
    ids = raw[:-1] if ended_by_eos else list(raw)
    truncated = (not ended_by_eos) and len(raw) >= max_new
    # A call that stopped on ``max_time`` (neither EOS nor the cap) is a timeout even
    # if the wall clock reads a hair under the deadline (registration: terminal).
    if seconds > deadline:
        timeout_reason = "wall_deadline_exceeded"
    elif not ended_by_eos and not truncated:
        timeout_reason = "max_time_stop"
    else:
        timeout_reason = None
    timed_out = timeout_reason is not None
    termination = "timeout" if timed_out else ("cap" if truncated else "eos")
    return {
        "text": session.tokenizer.decode(ids, skip_special_tokens=True),
        "generated_token_ids": ids,
        "generated_token_ids_raw": raw,
        "eos_token_ids": stops,
        "ended_by_eos": ended_by_eos,
        "prompt_tokens": session.last["prompt_tokens"],
        "n_generated": len(ids),
        "n_generated_raw": len(raw),
        "timed_out": timed_out,
        "timeout_reason": timeout_reason,
        "truncated": truncated,
        "termination": termination,
        "seconds": seconds,
    }


def load_package(hub: Path):
    import torch
