def frozen_chain(items_path: Path, qualification_path: Path) -> dict:
    """Load and verify the freeze chain (finding 5) or exit."""
    frozen = json.loads(items_path.read_text())
    qual = json.loads(qualification_path.read_text())
    problems = items4c.verify_frozen(frozen, qual, screen._sha256(qualification_path))
    if problems:
        raise SystemExit("frozen manifest chain broken: " + "; ".join(problems))
    return {"frozen": frozen, "qualification": qual}


