# ruff: noqa: E501
"""Salience (LEDGER-PLAN.md component A): does a sentence state a persistent,
checkable requirement the model must honor in its output?

Design constraints (the whole point, see LEDGER-PLAN.md):
* features are LINGUISTIC and benchmark-agnostic: imperative/verb class,
  modal obligation, prohibition, quantifier binding, numerals, quoted literals,
  reference to the output, text-form nouns, person, narrative markers;
* NO neural nets, no external calls, no new dependencies (numpy only);
* the synthetic corpora's "Constraint:" marker is stripped at load time and is
  never a feature; all features are computed on case-folded text so the
  corpora's capitalisation / final-punctuation artifacts cannot leak;
* logistic regression by full-batch gradient descent from zero init: bitwise
  deterministic and seed-free (``seed`` is accepted for API parity only).

Committed weights live in ``salience_weights.json`` next to this module and are
regenerated by ``python -m stencil.salience`` (tests assert the file matches a
refit bitwise).

Known limits (measured on hand-labeled Multi-IF turn-1 sentences, see
tests/test_salience.py): precision ~0.92-0.96, recall ~0.75.  It is
UNDER-inclusive by design.  It misses (a) constraints embedded in a task
sentence whose lead verb is a production verb ("Write a blog post ... with at
least 300 words"), (b) tone/manner directives with no form vocabulary ("Be
angry about it"), (c) compound task+constraint sentences.  It fires on
markdown/list fragments ("* Bullet 1") and on continuation tasks naming a
structural unit ("Now add a brief closing section ...").  It cannot tell the
addressee: run it on USER turns only — instruction echoes inside model
responses are imperatives too and are classified as such.
"""
from __future__ import annotations

import glob
import json
