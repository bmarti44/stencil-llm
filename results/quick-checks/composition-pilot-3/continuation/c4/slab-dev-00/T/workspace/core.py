def step_3(x):
   """Map each integer v to v * 9 + 2, preserving order.

   Args:
      x (list): A list of integers.

   Returns:
      list: A list of integers where each element is transformed by v * 9 + 2.

   Raises:
      TypeError: If any element in the list is not an integer.
   """
   if not all(isinstance(v, int) for v in x):
      raise TypeError("All elements in the list must be integers.")
   return [v * 9 + 2 for v in x]
